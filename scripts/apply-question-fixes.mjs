// ============ Apply fixes ============
let appliedCount = 0;
let notFoundIds = [];

for (const fix of FIXES) {
  // Find the question block by id
  const idPattern = new RegExp(`(id:\\s*"${fix.qId}"[\\s\\S]*?options:\\s*\\[)([\\s\\S]*?)(\\],\\s*correctIndex:\\s*)(\\d+)`);
  const match = src.match(idPattern);
  if (!match) {
    notFoundIds.push(fix.qId);
    continue;
  }

  // Build new options array text
  const newOptionsText = "\n      " +
    fix.newOptions.map(opt => `"${opt.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`).join(",\n      ") +
    "\n    ";

  // Build replacement
  const replacement = match[1] + newOptionsText + match[3] + fix.correctIndex;
  src = src.replace(idPattern, replacement);
  appliedCount++;
}

writeFileSync(file, src, "utf8");

console.log(`=== RESULTS ===`);
console.log(`Applied: ${appliedCount}/${FIXES.length} fixes`);
if (notFoundIds.length > 0) {
  console.log(`Not found: ${notFoundIds.join(", ")}`);
}
