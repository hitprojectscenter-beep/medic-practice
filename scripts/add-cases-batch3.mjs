function caseToTS(c) {
  const points = c.points.map(([label, keywords, weight, rationale]) =>
    `      { label: "${N(label)}", keywords: [${keywords.map(k => `"${N(k)}"`).join(", ")}], weight: "${weight}", rationale: "${N(rationale)}" }`
  ).join(",\n");
  const redFlags = (c.redFlags || []).map(f => `"${N(f)}"`).join(", ");
  return `  {
    id: "${c.id}",
    topic: "${N(c.topic)}",
    title: "${N(c.title)}",
    scenario: "${N(c.scenario)}",
    patient: { age: ${c.age}, sex: "${c.sex}", vitalsAtArrival: "${N(c.vitals)}" },
    expectedPoints: [
${points}
    ],
    redFlags: [${redFlags}],
    modelAnswer: "${N(c.modelAnswer)}"
  }`;
}

function extrasToTS(c) {
  const diff = c.differential.map(d =>
    `      { label: "${N(d.label)}", correct: ${d.correct}, explanation: "${N(d.explanation)}" }`
  ).join(",\n");
  const resps = c.responses.map(r => {
    const answer = r[r.length - 1];
    const keywords = r.slice(0, -1);
    return `      { keywords: [${keywords.map(k => `"${N(k)}"`).join(", ")}], answer: "${N(answer)}" }`;
  }).join(",\n");
  return `  "${c.id}": {
    dispatcherIntro: "${N(c.intro)}",
    differentialDiagnosis: [
${diff}
    ],
    patientResponses: [
${resps}
    ]
  }`;
}

let casesSrc = readFileSync("data/cases.ts", "utf8");
let extrasSrc = readFileSync("data/case-extras.ts", "utf8");

const caseTSBlocks = CASES.map(caseToTS).join(",\n\n");
const newCasesContent = ",\n\n  // === Batch 3 cases (auto-generated) ===\n" + caseTSBlocks + "\n";
casesSrc = casesSrc.replace(/(\s+)\];\s*(\n\s*export const getCaseById)/, `$1${newCasesContent}];$2`);

const extrasTSBlocks = CASES.map(extrasToTS).join(",\n\n");
const newExtrasContent = ",\n\n  // === Batch 3 extras (auto-generated) ===\n" + extrasTSBlocks + "\n";
extrasSrc = extrasSrc.replace(/(\s+)\}\s*(\n\};)/, `$1}${newExtrasContent}$2`);

writeFileSync("data/cases.ts", casesSrc, "utf8");
